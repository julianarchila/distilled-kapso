#!/usr/bin/env -S node --conditions=bun
/**
 * Writes packages/kapso/patches/001-whatsapp-message.json.
 *
 * Kapso's `WhatsappMessage` schema lists its `properties` next to
 * `anyOf: [{ required: [to] }, { required: [recipient] }]`. That `anyOf` only
 * says "send `to` or `recipient`", but distilled's OpenAPI converter reads
 * every `anyOf` as a union, finds no properties in either branch, and turns
 * the whole message into `smithy.api#Document`, so `sendMessage` takes
 * `unknown`.
 *
 * This script converts the spec twice, as is and with that one `anyOf`
 * dropped, and writes the difference as an RFC-6902 patch: the shapes the
 * second conversion adds, and the body member it retargets. The patch is
 * exactly the model a converter that treats required-only branches as a
 * constraint would produce. Once the converter does that, `pnpm
 * patches:audit` reports the patch as unneeded and it goes.
 *
 * Re-run after the spec changes:
 *   node --conditions=bun scripts/derive-whatsapp-message-patch.ts
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { convertOpenApiToSmithy } from "@distilled.cloud/dev/codegen/openapi";
import { parse } from "yaml";

const pkg = path.resolve(import.meta.dirname, "../packages/kapso");
const NS = "com.kapso.whatsapp";
const options = {
  namespace: NS,
  serviceName: "WhatsApp",
  skipDeprecated: true,
  headerParams: true,
  binaryTypes: true,
  statusToErrorClass: {},
  deferNaming: true,
} as const;

const text = fs.readFileSync(
  path.join(pkg, "specs/spec-mirror-kapso/specs/openapi-whatsapp.yaml"),
  "utf8",
);
const asIs: any = convertOpenApiToSmithy(parse(text), options);
const fixedSpec = parse(text);
delete fixedSpec.components.schemas.WhatsappMessage.anyOf;
const fixed: any = convertOpenApiToSmithy(fixedSpec, options);

if (!Array.isArray(parse(text).components?.schemas?.WhatsappMessage?.anyOf)) {
  throw new Error(
    "WhatsappMessage has no anyOf any more: the patch may be unneeded, re-check the spec",
  );
}

// Every shape the fixed conversion adds, and every shape it changes
// (SendMessageRequestBody, whose WhatsappMessage case stops being a Document).
const added = Object.keys(fixed.shapes).filter((id) => !(id in asIs.shapes));
const changed = Object.keys(fixed.shapes).filter(
  (id) => id in asIs.shapes && JSON.stringify(fixed.shapes[id]) !== JSON.stringify(asIs.shapes[id]),
);

const patch = {
  description:
    "Type sendMessage's message body. The spec's WhatsappMessage schema has `properties` and `anyOf: [{ required: [to] }, { required: [recipient] }]`, which only says a send names `to` or `recipient`. The converter reads that anyOf as a union with no properties and turns the message into a Document, so sendMessage took `unknown`. These are the shapes the converter emits for WhatsappMessage with the anyOf ignored (generated by scripts/derive-whatsapp-message-patch.ts). A live text send of 2026-11-17 with these members was accepted.",
  patches: [
    ...added.map((id) => ({ op: "add", path: `/shapes/${id}`, value: fixed.shapes[id] })),
    ...changed.map((id) => ({ op: "replace", path: `/shapes/${id}`, value: fixed.shapes[id] })),
  ],
};
const out = path.join(pkg, "patches/001-whatsapp-message.json");
fs.writeFileSync(out, JSON.stringify(patch, null, 2) + "\n");
console.log(`${out}: ${added.length} shapes added, ${changed.length} replaced`);
